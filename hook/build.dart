// ── Native: cargo build of the vendored icu_capi ─────────────────

/// Compiles `icu_capi` from `vendor/icu4x` straight to [dest].
///
/// Static builds (iOS's link-mode preference) and no_std targets use the
/// pinned nightly with -Zbuild-std, mirroring upstream ICU4X's own
/// build.sh; everything else builds a cdylib on stable.
Future<void> _compileIcuCapi(
  BuildInput input,
  LinkMode linkMode,
  File dest,
) async {
  final submodule = input.packageRoot.resolve('vendor/icu4x/');
  final rustTarget = _toRustTarget(input.config.code);
  final isNoStd = _noStdTargets.contains(rustTarget);
  final buildStatic = linkMode is StaticLinking;
  final out = dest.uri;

  // Cargo's target dir lives in outputDirectoryShared so:
  //   1. The vendored submodule's working tree stays clean.
  //   2. Incremental cargo cache survives across hook invocations.
  //   3. Different consumer apps share the same cache.
  final cargoTargetDir = input.outputDirectoryShared
      .resolve('cargo-target/')
      .toFilePath();
  final cargoEnv = {
    'CARGO_TARGET_DIR': cargoTargetDir,
    if (isNoStd) 'RUSTFLAGS': '-Zunstable-options -Cpanic=immediate-abort',
  };

  // Android: point cargo at the NDK clang driver Flutter provides. Without
  // this cargo links Android targets with the HOST `cc` (mingw ld / host
  // clang), which rejects the ELF flags and produces host-linked objects.
  if (input.config.code.targetOS == OS.android) {
    final cc = input.config.code.cCompiler;
    if (cc != null) {
      final compilerDir = p.dirname(p.fromUri(cc.compiler));
      final ndkTriple = rustTarget == 'armv7-linux-androideabi'
          ? 'armv7a-linux-androideabi'
          : rustTarget;
      // The NDK per-API clang driver is a `.cmd` batch wrapper on Windows
      // hosts (e.g. aarch64-linux-android21-clang.cmd); passing the bare name
      // makes cargo fail with "could not exec the linker ... program not
      // found". Append the host executable extension so Android cross-compiles
      // link from a Windows host as well as Linux/macOS. Platform.isWindows
      // here is the BUILD host (which runs cargo), not the Android target.
      final clangExt = Platform.isWindows ? '.cmd' : '';
      final envKey =
          'CARGO_TARGET_${rustTarget.toUpperCase().replaceAll('-', '_')}';
      cargoEnv['${envKey}_LINKER'] = p.join(
        compilerDir,
        '${ndkTriple}21-clang$clangExt',
      );
      cargoEnv['${envKey}_AR'] = p.join(compilerDir, 'llvm-ar');
      _log.info('NDK linker: ${cargoEnv['${envKey}_LINKER']}');
    }
  }

  final workdir = Directory.fromUri(submodule);
  final crateType = buildStatic ? 'staticlib' : 'cdylib';

  _log.info(
    'building icu_capi for $rustTarget '
    '($crateType, ${isNoStd ? 'no_std nightly' : 'std stable'})',
  );

  if (buildStatic || isNoStd) {
    await _run('rustup', [
      'toolchain',
      'install',
      '--no-self-update',
      _pinnedNightly,
      '--component',
      'rust-src',
    ], workdir);
  }

  await _run('rustup', [
    'target',
    'add',
    rustTarget,
    if (buildStatic || isNoStd) ...['--toolchain', _pinnedNightly],
  ], workdir);

  final addedFeatures = isNoStd
      ? const ['libc_alloc', 'looping_panic_handler']
      : const ['simple_logger'];
  final allFeatures = _resolveCargoFeatures(input, addedFeatures).join(',');

  await _run(
    'cargo',
    [
      if (buildStatic || isNoStd) '+$_pinnedNightly',
      'rustc',
      '--manifest-path=ffi/capi/Cargo.toml',
      '--crate-type=$crateType',
      '--release',
      '--config=profile.release.panic="abort"',
      '--config=profile.release.codegen-units=1',
      '--no-default-features',
      '--features=$allFeatures',
      if (isNoStd) '-Zbuild-std=core,alloc',
      if (buildStatic || isNoStd) ...['-Zbuild-std=std,panic_abort'],
      '--target=$rustTarget',
      '--',
      '--emit',
      'link=${out.toFilePath(windows: Platform.isWindows)}',
    ],
    workdir,
    environment: cargoEnv,
  );

  if (!dest.existsSync()) {
    throw StateError(
      'cargo claimed success but output missing at $out. '
      'Inspect logs above for cargo warnings.',
    );
  }

  _log.info('compiled: ${out.toFilePath()}');
}

// ── Web: the WASM binary ─────────────────────────────────────────

/// The web_assets/ artifact behind a release asset name. Release assets
/// carry the `wasm-` flatten prefix the pipeline adds to files from the
/// wasm build's output dir; stripping it recovers the on-disk name
/// (`wasm-icu4x-lean.wasm` → `icu4x-lean.wasm`).
String _sourceArtifact(String assetName) =>
    assetName.startsWith('wasm-') ? assetName.substring(5) : assetName;

Future<void> _compileWasm(
  Uri packageRoot,
  File dest, {
  required String assetName,
  required bool lean,
}) async {
  final sourceName = _sourceArtifact(assetName);
  final existing = File.fromUri(packageRoot.resolve('web_assets/$sourceName'));

  // Contributor has locally built WASM — copy directly.
  if (existing.existsSync()) {
    dest.parent.createSync(recursive: true);
    existing.copySync(dest.path);
    return;
  }

  // Compile from source (nightly Rust; the tool self-provisions).
  final script = File.fromUri(packageRoot.resolve('tool/build_wasm.dart'));
  if (!script.existsSync()) {
    throw StateError(
      'tool/build_wasm.dart not found. Cannot compile WASM.\n'
      'Install from pub.dev or use a git tag with pre-built binaries.',
    );
  }

  final result = await Process.run('dart', [
    'run',
    'tool/build_wasm.dart',
    if (lean) '--lean',
  ], workingDirectory: p.fromUri(packageRoot));
  if (result.exitCode != 0) {
    throw StateError(
      'WASM compilation failed (exit ${result.exitCode}).\n'
      'stderr: ${result.stderr}\n\n'
      'Ensure Rust is installed: https://rustup.rs',
    );
  }

  if (!existing.existsSync()) {
    throw StateError(
      'WASM compiled but $sourceName not found at ${existing.path}',
    );
  }
  dest.parent.createSync(recursive: true);
  existing.copySync(dest.path);
}

