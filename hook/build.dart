/// Throws with an actionable error if the bindings haven't been generated.
void _verifyBindings(Uri bindingsBarrel) {
  if (!File.fromUri(bindingsBarrel).existsSync()) {
    throw StateError(
      'Diplomat-generated bindings not found at $bindingsBarrel.\n'
      'Run: fvm dart run tool/regen_bindings.dart',
    );
  }
}

/// Register every file `package:hooks` should hash to decide whether the
/// hook needs to re-run. Must over-approximate cargo's inputs and must
/// exist BEFORE the first build — never derive this list from build
/// outputs, or caching goes circular and binaries go stale.
///
/// The vendor walk only runs when the vendor source is on disk. It
/// always is for pub installs (the vendor ships in the tarball); it's
/// absent only on a git clone without `--recursive`.
void _trackDependencies({
  required BuildOutputBuilder output,
  required Uri packageRoot,
  required Uri bindingsBarrel,
}) {
  output.dependencies.addAll([
    bindingsBarrel,
    packageRoot.resolve('pubspec.yaml'),
    packageRoot.resolve('build.json'),
    packageRoot.resolve('hook/build.dart'),
    packageRoot.resolve('lib/src/hook/asset_hashes.dart'),
    packageRoot.resolve('lib/src/hook/resolver.dart'),
  ]);

  if (!hasVendorSource(packageRoot)) return;

  final submodule = packageRoot.resolve('vendor/icu4x/');
  // Workspace + crate configs: feature edits, toolchain bumps, and linker
  // flags change the binary without touching any .rs file.
  const configs = [
    'Cargo.toml',
    'Cargo.lock',
    'rust-toolchain.toml',
    'rust-toolchain',
    '.cargo/config.toml',
    '.cargo/config',
    'ffi/capi/Cargo.toml',
    'ffi/capi/build.rs',
  ];
  for (final file in configs) {
    final uri = submodule.resolve(file);
    if (File.fromUri(uri).existsSync()) {
      output.dependencies.add(uri);
    }
  }
  for (final dirName in _trackedRustDirs) {
    final dir = Directory.fromUri(submodule.resolve('$dirName/'));
    if (!dir.existsSync()) continue;
    for (final entity in dir.listSync(recursive: true, followLinks: false)) {
      // What cargo actually reads: sources, baked-data includes, and
      // per-crate manifests. NOT every file — provider/source/ alone is
      // 7k+ files of datagen-only CLDR input that cargo never touches,
      // and package:hooks content-hashes every dependency per run.
      if (entity is File &&
          (entity.path.endsWith('.rs') ||
              entity.path.endsWith('.rs.data') ||
              entity.path.endsWith('Cargo.toml'))) {
        output.dependencies.add(entity.uri);
      }
    }
  }
}

// ══════════════════════════════════════════════════════════════════
// § 5 — CodeConfig mapping
// ══════════════════════════════════════════════════════════════════

/// Whether this build bakes the CLDR in. Reads the `bundleCldrData`
/// user_define from the consumer's pubspec:
///
/// ```yaml
/// hooks:
///   user_defines:
///     icu_kit:
///       bundleCldrData: false   # lean binary; use IcuData.lazy at runtime
/// ```
///
/// Default is `true` — full CLDR baked in. Set to `false` for the lean
/// binary without the ~19 MB CLDR statics; apps must then init with
/// `IcuData.lazy(...)` to load per-locale postcards on demand.
bool _bundleCldr(BuildInput input) {
  final raw = input.userDefines['bundleCldrData'];
  return switch (raw) {
    null => true,
    final bool b => b,
    'true' || 'True' => true,
    'false' || 'False' => false,
    _ => throw ArgumentError('''
icu_kit user_define `bundleCldrData` must be a bool, got: $raw

Set it in your app's pubspec.yaml:

* Fat binary (default) — full CLDR baked in, works offline out of the box:
```
hooks:
  user_defines:
    icu_kit:
      bundleCldrData: true
```

* Lean binary — no CLDR statics (~19 MB smaller); the app must init with
  `IcuData.lazy(...)` and load per-locale postcards at runtime:
```
hooks:
  user_defines:
    icu_kit:
      bundleCldrData: false
```
'''),
  };
}

/// Resolve the full cargo feature list for this build from build.json's
/// `native` / `nativeLean` sets (the single source of truth shared with
/// tool/compile_rust.sh and the S7 analyze gate), plus per-target
/// additions.
List<String> _resolveCargoFeatures(BuildInput input, List<String> added) {
  final bundleCldr = _bundleCldr(input);
  _log.info(
    'cldr bundling: ${bundleCldr ? 'ON (compiled_data)' : 'OFF (lazy only)'}',
  );
  return [
    ...(bundleCldr ? _nativeFeatures : _nativeLeanFeatures).split(','),
    ...added,
  ];
}

/// Rust targets that require `-Zbuild-std` and a no_std-friendly feature
/// set. ICU4X's own build.sh treats these specially.
const _noStdTargets = <String>{
  'riscv64-linux-android',
  'riscv64gc-unknown-linux-gnu',
  'wasm32-unknown-unknown',
};

/// The link mode this build wants, straight from the preference. iOS
/// builds prefer static (a staticlib lands in the app binary); every
/// other Flutter target prefers dynamic. Never force static merely
/// because linking is enabled — release/AOT builds route the SAME
/// dynamic asset through the passthrough link hook.
LinkMode _linkMode(CodeConfig code) {
  return switch (code.linkModePreference) {
    LinkModePreference.dynamic ||
    LinkModePreference.preferDynamic => DynamicLoadingBundled(),
    LinkModePreference.static ||
    LinkModePreference.preferStatic => StaticLinking(),
    _ => DynamicLoadingBundled(),
  };
}

/// Map Dart's `(targetOS, targetArchitecture)` to Cargo's Rust target triple.
String _toRustTarget(CodeConfig code) {
  if (code.targetOS == OS.iOS &&
      code.targetArchitecture == Architecture.arm64 &&
      code.iOS.targetSdk == IOSSdk.iPhoneSimulator) {
    return 'aarch64-apple-ios-sim';
  }
  return switch ((code.targetOS, code.targetArchitecture)) {
    (OS.android, Architecture.arm) => 'armv7-linux-androideabi',
    (OS.android, Architecture.arm64) => 'aarch64-linux-android',
    (OS.android, Architecture.ia32) => 'i686-linux-android',
    (OS.android, Architecture.x64) => 'x86_64-linux-android',
    (OS.iOS, Architecture.arm64) => 'aarch64-apple-ios',
    (OS.iOS, Architecture.x64) => 'x86_64-apple-ios',
    (OS.linux, Architecture.arm) => 'armv7-unknown-linux-gnueabihf',
    (OS.linux, Architecture.arm64) => 'aarch64-unknown-linux-gnu',
    (OS.linux, Architecture.x64) => 'x86_64-unknown-linux-gnu',
    (OS.macOS, Architecture.arm64) => 'aarch64-apple-darwin',
    (OS.macOS, Architecture.x64) => 'x86_64-apple-darwin',
    (OS.windows, Architecture.arm64) => 'aarch64-pc-windows-msvc',
    (OS.windows, Architecture.x64) => 'x86_64-pc-windows-msvc',
    (_, _) => throw UnimplementedError(
      'icu_kit: no Rust target mapping for '
      '${code.targetOS} ${code.targetArchitecture}',
    ),
  };
}

/// Release-asset key for this config: the target key, plus `-lean` when
/// the CLDR is not bundled. Combined with the platform library filename
/// it names the GitHub Release asset (e.g.
/// `macos-arm64-libicu_capi.dylib`, `android-arm64-lean-libicu_capi.so`).
/// tool/compile_rust.sh writes its outputs under these same keys.
String _assetKey(CodeConfig code, {required bool lean}) {
  final base = _targetKey(code);
  return lean ? '$base-lean' : base;
}

String _targetKey(CodeConfig code) {
  if (code.targetOS == OS.iOS &&
      code.targetArchitecture == Architecture.arm64 &&
      code.iOS.targetSdk == IOSSdk.iPhoneSimulator) {
    return 'ios-sim-arm64';
  }
  return switch ((code.targetOS, code.targetArchitecture)) {
    (OS.android, Architecture.arm) => 'android-arm',
    (OS.android, Architecture.arm64) => 'android-arm64',
    (OS.android, Architecture.ia32) => 'android-x86',
    (OS.android, Architecture.x64) => 'android-x64',
    (OS.iOS, Architecture.arm64) => 'ios-arm64',
    (OS.iOS, Architecture.x64) => 'ios-sim-x64',
    (OS.linux, Architecture.arm) => 'linux-arm',
    (OS.linux, Architecture.arm64) => 'linux-arm64',
    (OS.linux, Architecture.x64) => 'linux-x64',
    (OS.macOS, Architecture.arm64) => 'macos-arm64',
    (OS.macOS, Architecture.x64) => 'macos-x64',
    (OS.windows, Architecture.arm64) => 'windows-arm64',
    (OS.windows, Architecture.x64) => 'windows-x64',
    (_, _) => throw UnsupportedError(
      'Unsupported: ${code.targetOS} ${code.targetArchitecture}',
    ),
  };
}

/// Run an external process with stdout/stderr streamed live, so cargo's
/// own progress + warnings show up under `flutter run` in real time
/// instead of buffering until completion.
Future<void> _run(
  String exe,
  List<String> args,
  Directory cwd, {
  Map<String, String>? environment,
}) async {
  _log.fine('  \$ $exe ${args.join(' ')}');
  final process = await Process.start(
    exe,
    args,
    workingDirectory: cwd.path,
    environment: environment,
    mode: ProcessStartMode.inheritStdio,
  );
  final code = await process.exitCode;
  if (code != 0) {
    throw ProcessException(exe, args, 'exit $code', code);
  }
}
