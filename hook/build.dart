// Build hook for icu_kit.
//
// ═══════════════════════════════════════════════════════════════════
// STRUCTURE
// ═══════════════════════════════════════════════════════════════════
//
//   main()           Flutter/Dart hook entry point (native targets only).
//                    Resolves the binary, registers it with the build.
//
//   resolveWeb()     Public API for bin/setup.dart (web assets).
//                    Same waterfall for the WASM binary, plus a plain
//                    copy of the committed Diplomat JS bindings — the
//                    browser serves web/ as static files, no
//                    registration needed.
//
//   _resolveNative() Private. Only main() calls this — the correct
//                    cache path and target config only exist inside
//                    the build hook. setup <native> delegates to
//                    `flutter build` which triggers main().
//
// ═══════════════════════════════════════════════════════════════════
// RESOLUTION WATERFALL (same for native and web)
// ═══════════════════════════════════════════════════════════════════
//
//   1. CACHED    — existing file, only with a PROOF: hash match, or
//                  no-hash-AND-no-sources (nothing better exists).
//                  When vendor sources are present and there is no
//                  hash, this step always falls through — freshness
//                  is cargo's question, never file-existence.
//   2. DOWNLOAD  — fetch from GitHub Releases; verified against the
//                  pinned hash at download time (or used with a loud
//                  warning when neither hash nor source exists) → cache
//   3. COMPILE   — vendor/icu4x/ exists → cargo → use it
//   4. SUBMODULE — .gitmodules exists → git init recursive → compile
//   5. ERROR     — nothing worked, clear message with options
//
//   --force skips step 1 (web only, via setup.dart).
//   Version 0.0.0 (dev) skips step 2 (no release exists) — so every
//   dev build lands on step 3 and cargo's fingerprint check decides
//   whether anything actually recompiles (~1s when nothing changed).
//
// ═══════════════════════════════════════════════════════════════════
// USER SCENARIOS
// ═══════════════════════════════════════════════════════════════════
//
//   pub.dev consumer (icu_kit: ^X.Y.Z):
//     Native: automatic via build hook. Downloads the prebuilt binary.
//             The vendored ICU4X source ships in the pub archive (same
//             model as pdf_manipulator), so compile-from-vendor is the
//             fallback when the download is unavailable (needs the
//             Rust toolchain).
//     Web:    manual `flutter pub run icu_kit:setup`.
//             Downloads the WASM; the JS bindings ship in the package.
//
//   Git tag consumer (ref: vX.Y.Z):
//     Same release binaries; the stamped tag carries the vendor as raw
//     source (submodule de-registered), so source builds work directly.
//
//   Git branch consumer (ref: dev, version 0.0.0):
//     Download skipped. Compiles from vendor source or inits
//     submodules first.
//
//   Contributor (path dependency):
//     Same as branch consumer. Always compiles from source.
//
// ═══════════════════════════════════════════════════════════════════
// STALENESS
// ═══════════════════════════════════════════════════════════════════
//
//   Native: fully automatic. The build re-runs the hook when a tracked
//     dependency changes. New assetHashes → hash mismatch →
//     re-downloads.
//
//   Web: NOT automatic. User must run `setup` after a package update.
//     Hash check detects stale files and re-resolves automatically.
//     Tracked: dart-lang/native#988 (WasmAsset/JsAsset support).
//
// ═══════════════════════════════════════════════════════════════════
// ASSET HASHES
// ═══════════════════════════════════════════════════════════════════
//
//   Flat Map<String, String> keyed by GitHub Release asset name.
//   Generated by the shared whuppi/ci release.sh (--update-tag-hashes)
//   from the GitHub Release API digests.
//
// ═══════════════════════════════════════════════════════════════════
// COMPILE DETAILS (preserved from the pre-waterfall hook)
// ═══════════════════════════════════════════════════════════════════
//
//   The compiled library is registered as a CodeAsset under the asset
//   name `src/runtime/native/bindings/lib.g.dart` — the Diplomat-generated
//   `@ffi.Native` annotations resolve symbols against it.
//
//   Cargo's intermediate `target/` lives in `outputDirectoryShared` so
//   the vendored submodule's working tree stays clean and incremental
//   caches survive across hook invocations.
//
//   Rebuild detection (contributors only): every *.rs, *.rs.data (baked
//   data include), and Cargo.toml under the tracked vendor dirs is a
//   dependency, plus the workspace configs (Cargo.toml/.lock,
//   rust-toolchain, .cargo/config, capi build.rs), the bindings barrel,
//   build.json, asset_hashes.dart, pubspec.yaml, and this hook.

import 'dart:convert';
import 'dart:io';

import 'package:code_assets/code_assets.dart';
import 'package:hooks/hooks.dart';
import 'package:logging/logging.dart';
import 'package:path/path.dart' as p;

import 'package:icu_kit/src/hook/asset_hashes.dart';
import 'package:icu_kit/src/hook/resolver.dart';

final _log = Logger('icu_kit:build');

/// The Dart asset path corresponding to our generated bindings library.
/// Diplomat's generated `@ffi.Native` symbols resolve against this asset.
/// Bindings live at lib/src/runtime/native/bindings/ — regenerated by
/// tool/regen_bindings.dart.
const _bindingsAssetName = 'src/runtime/native/bindings/lib.g.dart';

/// Subdirectories of the vendored ICU4X submodule tracked as build
/// dependencies. Any file change under these paths triggers a rebuild
/// via `package:hooks` content-hash comparison.
const _trackedRustDirs = ['components', 'utils', 'provider', 'ffi/capi'];

// ── build.json — single source of truth for all build constants ──
// Loaded once per hook invocation. Every constant that's shared with
// tool/compile_rust.sh and the release pipeline lives here.
Map<String, dynamic>? _buildConfig;
late String _crateName;
late String _repo;
late String _pinnedNightly;
late Map<String, String> _webAssets;
late Map<String, String> _webAssetsLean;
late Set<String> _wasmBuildOutputs;
late String _nativeFeatures;
late String _nativeLeanFeatures;

void _loadBuildConfig(Uri packageRoot) {
  if (_buildConfig != null) return;
  final file = File.fromUri(packageRoot.resolve('build.json'));
  final json = jsonDecode(file.readAsStringSync()) as Map<String, dynamic>;
  _buildConfig = json;
  _crateName = json['crate'] as String;
  _repo = json['repo'] as String;
  _pinnedNightly = json['nightlyToolchain'] as String;
  _webAssets = Map<String, String>.from(json['web'] as Map);
  _webAssetsLean = Map<String, String>.from(json['webLean'] as Map);
  _wasmBuildOutputs = Set<String>.from(json['wasmBuildOutputs'] as List);
  final features = json['features'] as Map;
  _nativeFeatures = features['native'] as String;
  _nativeLeanFeatures = features['nativeLean'] as String;
}

String _downloadUrl(String version, String assetName) =>
    'https://github.com/$_repo/releases/download/v$version/$assetName';

// ══════════════════════════════════════════════════════════════════
// § 1 — Hook entry point (native only)
//
// Called automatically for iOS, Android, macOS, Linux, Windows.
// NOT called for web — web goes through resolveWeb() via setup.dart.
// ══════════════════════════════════════════════════════════════════

void main(List<String> args) async {
  await build(args, (BuildInput input, BuildOutputBuilder output) async {
    if (!input.config.buildCodeAssets) return;

    _loadBuildConfig(input.packageRoot);

    final packageRoot = input.packageRoot;
    final bindingsBarrel = packageRoot.resolve(
      'lib/src/runtime/native/bindings/lib.g.dart',
    );
    _verifyBindings(bindingsBarrel);

    final codeConfig = input.config.code;
    final rustTarget = _toRustTarget(codeConfig);
    final linkMode = _linkMode(codeConfig);
    final libFileName = codeConfig.targetOS.libraryFileName(
      _crateName,
      linkMode,
    );
    final lean = !_bundleCldr(input);
    final outFile = File.fromUri(input.outputDirectory.resolve(libFileName));

    // ── Resolve the binary (cache, download, or compile) ──
    await _resolveNative(
      input: input,
      version: readVersion(packageRoot),
      assetName: '${_assetKey(codeConfig, lean: lean)}-$libFileName',
      dest: outFile,
      cacheFile: File.fromUri(
        input.outputDirectoryShared.resolve(
          'prebuilt/$rustTarget${lean ? '-lean' : ''}/$libFileName',
        ),
      ),
      linkMode: linkMode,
    );

    // ── Register with the build ──
    output.assets.code.add(
      CodeAsset(
        package: input.packageName,
        name: _bindingsAssetName,
        linkMode: linkMode,
        file: outFile.uri,
      ),
      routing: input.config.linkingEnabled
          ? ToLinkHook(input.packageName)
          : const ToAppBundle(),
    );

    _trackDependencies(
      output: output,
      packageRoot: packageRoot,
      bindingsBarrel: bindingsBarrel,
    );
  });
}

// ══════════════════════════════════════════════════════════════════
// § 2 — Resolution
// ══════════════════════════════════════════════════════════════════

// ── Native (private) ─────────────────────────────────────────────
// Not public because the correct cache path, target triple, link
// mode, and NDK config all come from the hook's BuildInput — which
// only exists inside the hook. Calling from outside writes to the
// wrong cache. setup <native> delegates to `flutter build` instead.
Future<void> _resolveNative({
  required BuildInput input,
  required String version,
  required String assetName,
  required File dest,
  required File cacheFile,
  required LinkMode linkMode,
}) async {
  await resolveAsset(
    ResolveRequest(
      assetName: assetName,
      downloadUrl: _downloadUrl(version, assetName),
      dest: dest,
      cacheFile: cacheFile,
      expectedHash: assetHashes[assetName],
      version: version,
      packageRoot: input.packageRoot,
      compile: (File d) => _compileIcuCapi(input, linkMode, d),
    ),
  );
}

// ── Web (public — called by bin/setup.dart) ──────────────────────
// Resolves the WASM binary into destDir (typically web/icu_kit/) via
// the waterfall, then copies the COMMITTED web assets — the Diplomat
// JS bindings tree (lib/, ~370 .mjs files) and diplomat.config.mjs —
// straight from the package. Those ship in the pub archive like any
// Dart source (per-file release assets would be absurd at that count),
// so their integrity rides the same trust as the package itself; only
// the gitignored WASM build artifact needs the download waterfall.
//
// Returns the number of files freshly resolved (0 = all cached).
//
// [lean] installs the no-CLDR wasm variant UNDER THE SAME local name
// (icu4x.wasm) — the runtime flavor probe detects which variant loaded,
// so nothing else (config, module URLs, bindings) changes. Switching
// variants later just re-runs setup; the hash check sees the mismatch
// against the other variant's hash and re-resolves.
Future<int> resolveWeb({
  required Uri packageRoot,
  required String version,
  required Directory destDir,
  bool force = false,
  bool lean = false,
}) async {
  _loadBuildConfig(packageRoot);

  if (!destDir.existsSync()) {
    destDir.createSync(recursive: true);
  }

  var installed = 0;

  for (final entry in (lean ? _webAssetsLean : _webAssets).entries) {
    final localName = entry.key;
    final assetName = entry.value;
    final dest = File(p.join(destDir.path, localName));

    assert(
      _wasmBuildOutputs.contains(_sourceArtifact(assetName)),
      'non-wasm web map entries need a copy fallback (see pdf_manipulator)',
    );

    final fresh = await resolveAsset(
      ResolveRequest(
        assetName: assetName,
        downloadUrl: _downloadUrl(version, assetName),
        dest: dest,
        expectedHash: assetHashes[assetName],
        version: version,
        packageRoot: packageRoot,
        force: force,
        compile: (File d) =>
            _compileWasm(packageRoot, d, assetName: assetName, lean: lean),
      ),
    );

    if (fresh) installed++;
  }

  installed += _copyCommittedWebAssets(packageRoot, destDir, force: force);
  return installed;
}

/// Copy the committed (non-WASM) web assets from the package's
/// web_assets/ into [destDir]: `diplomat.config.mjs` + the `lib/`
/// bindings tree. Overwrites when [force] or when the source is newer.
int _copyCommittedWebAssets(
  Uri packageRoot,
  Directory destDir, {
  required bool force,
}) {
  final webAssets = Directory.fromUri(packageRoot.resolve('web_assets/'));
  if (!webAssets.existsSync()) {
    throw StateError(
      'web_assets/ missing from the icu_kit package at $webAssets — '
      'the install is broken; reinstall the package.',
    );
  }

  var copied = 0;
  for (final entity in webAssets.listSync(recursive: true)) {
    if (entity is! File) continue;
    final rel = p.relative(entity.path, from: webAssets.path);
    // Waterfall-owned build artifacts (both wasm variants) — never
    // copied as committed assets, even when a contributor checkout has
    // them built locally.
    if (_wasmBuildOutputs.contains(rel)) continue;
    final dest = File(p.join(destDir.path, rel));
    if (!force &&
        dest.existsSync() &&
        !entity.lastModifiedSync().isAfter(dest.lastModifiedSync())) {
      continue;
    }
    dest.parent.createSync(recursive: true);
    entity.copySync(dest.path);
    copied++;
  }
  return copied;
}

